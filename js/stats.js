/**
 * PMF отрицательного биномиального распределения.
 * P(X = k) для X ~ NegBinom(r, p).
 */
export function negBinomPMF(k, r, p) {
  let logC = 0;
  for (let i = 1; i <= k; i++) logC += Math.log(r + i - 1) - Math.log(i);
  return Math.exp(logC + r * Math.log(p) + k * Math.log(1 - p));
}

/**
 * Приблизительный квантиль Gamma-распределения (Wilson-Hilferty).
 * shape — параметр формы, p — вероятность (0..1).
 */
export function gammaQuantile(shape, p) {
  const z = normQ(p);
  const c = 1 - 1 / (9 * shape) + z / (3 * Math.sqrt(shape));
  return shape * c * c * c;
}

/**
 * Квантиль стандартного нормального распределения (Acklam's approximation).
 * Точность ~1.15e-9 на всём диапазоне (0, 1).
 */
export function normQ(p) {
  const a = [
    -3.969683028665376e1, 2.209460984245205e2, -2.759285104469687e2,
    1.38357751867269e2, -3.066479806614716e1, 2.506628277459239,
  ];
  const b = [
    -5.447609879822406e1, 1.615858368580409e2, -1.556989798598866e2,
    6.680131188771972e1, -1.328068155288572e1,
  ];
  const c = [
    -7.784894002430293e-3, -3.223964580411365e-1, -2.400758277161838,
    -2.549732539343734, 4.374664141464968, 2.938163982698783,
  ];
  const d = [
    7.784695709041462e-3, 3.224671290700398e-1, 2.445134137142996,
    3.754408661907416,
  ];
  const pl = 0.02425,
    ph = 1 - pl;
  let q, r;

  if (p < pl) {
    q = Math.sqrt(-2 * Math.log(p));
    return (
      (((((c[0] * q + c[1]) * q + c[2]) * q + c[3]) * q + c[4]) * q + c[5]) /
      ((((d[0] * q + d[1]) * q + d[2]) * q + d[3]) * q + 1)
    );
  }
  if (p > ph) {
    q = Math.sqrt(-2 * Math.log(1 - p));
    return (
      -(((((c[0] * q + c[1]) * q + c[2]) * q + c[3]) * q + c[4]) * q + c[5]) /
      ((((d[0] * q + d[1]) * q + d[2]) * q + d[3]) * q + 1)
    );
  }
  q = p - 0.5;
  r = q * q;
  return (
    ((((((a[0] * r + a[1]) * r + a[2]) * r + a[3]) * r + a[4]) * r + a[5]) *
      q) /
    (((((b[0] * r + b[1]) * r + b[2]) * r + b[3]) * r + b[4]) * r + 1)
  );
}
